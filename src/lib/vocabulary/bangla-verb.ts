/** A word outside the list, by the regular pattern: সাজানো → সাজাল / সাজিয়েছে, কাটা → কাটল / কাটেছে. */
function regularForms(word: string): [string, string] | null {
  if (word.endsWith("ানো")) return [`${word.slice(0, -2)}ল`, `${word.slice(0, -3)}িয়েছে`];
  if (word.endsWith("া") && word.length > 1) return [`${word.slice(0, -1)}ল`, `${word.slice(0, -1)}েছে`];
  return null;
}

/** "/"-separated meanings, ignoring a "/" inside brackets. */
function alternatives(meaning: string) {
  const parts: string[] = [];
  let depth = 0;
  let current = "";
  for (const char of meaning) {
    if (char === "(") depth++;
    if (char === ")") depth = Math.max(0, depth - 1);
    if (char === "/" && depth === 0) { parts.push(current.trim()); current = ""; continue; }
    current += char;
  }
  parts.push(current.trim());
  return parts.filter(Boolean);
}

/** One meaning with its last verb word (outside brackets) changed, or null if that word isn't a verb form we know. */
function inflect(meaning: string, which: 0 | 1) {
  const tokens = meaning.split(/(\s+|\([^)]*\))/).filter((token) => token !== undefined && token !== "");
  for (let index = tokens.length - 1; index >= 0; index--) {
    const token = tokens[index];
    if (!token.trim() || token.startsWith("(")) continue;
    const found = forms[token] ?? regularForms(token);
    if (!found) return null;
    return [...tokens.slice(0, index), found[which], ...tokens.slice(index + 1)].join("");
  }
  return null;
}

/** English verbs whose Bangla past doesn't follow from the meaning word by word ("was" is ছিল, not হলো). */
const byVerb: Record<string, { past: string; pastParticiple: string }> = {
  be: { past: "ছিল", pastParticiple: "হয়েছে / থেকেছে" },
  have: { past: "ছিল / খেল", pastParticiple: "পেয়েছে / খেয়েছে" },
};

/** Bangla for an English verb's past (simple past) and past participle (perfect), from its meaning. */
export function banglaVerbForms(meaning: string, present?: string): { past: string; pastParticiple: string } {
  const fixed = present ? byVerb[present.toLowerCase()] : undefined;
  if (fixed) return fixed;
  const each = alternatives(meaning);
  const past = each.map((alt) => inflect(alt, 0)).filter(Boolean).join(" / ");
  const pastParticiple = each.map((alt) => inflect(alt, 1)).filter(Boolean).join(" / ");
  return { past, pastParticiple };
}

